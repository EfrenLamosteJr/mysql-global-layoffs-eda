-- EXPLANATORY DATA ANALYSIS
-- IN THIS PART WE JUST STUDY THE DATA, CHECK WHAT HAPPEN AND UNDERSTAND IT

SELECT *
FROM layoffs_staging2;

-- CHECKING THE HIGHEST LAYOFFS
SELECT MAX(total_laid_off), MAX(percentage_laid_off)
FROM layoffs_staging2
;
-- 1 PERCENTAGE_LAID_OFF MEANS 100% OF EMPLOYEE HAS BEEN LAYED OFF IT MEAN THE COMPANY SHUTDOWN
SELECT *
FROM layoffs_staging2
WHERE percentage_laid_off = 1
ORDER BY total_laid_off	DESC
;
-- WE CHECK TOTAL COMPANY HAS LAYOFFS
SELECT company, SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY company
ORDER BY 2 DESC;

-- WE CHECK THE START AND END OF RECOND DATE OF DATA
-- THE YEAR SHOWS WHEN IT HITS BY PANDEMIC
-- IT EXPLAIN WHY COMPANY LAYOFFS A LOT OF EMPLOYEE
SELECT MIN(`date`), MAX(`date`)
FROM layoffs_staging2;
-- HERE WE CHECK WHAT INDUSTRY HIT THE MOST
SELECT industry, SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY industry
ORDER BY 2 DESC;
-- HERE WE CHECK WHAT COUNTRY HIT THE MOST
SELECT country, SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY country
ORDER BY 2 DESC;
-- HERE WE CHECK WHAT YEAR HIT THE MOST
SELECT YEAR(`date`), SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY YEAR(`date`)
ORDER BY 1 DESC;
-- HERE WE CHECK WHAT STAGE HIT THE MOST
SELECT stage, SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY stage
ORDER BY 2 DESC;
-- WE CANT USE percentage_laid_off FOR ANALYSIS SINCE WE DONT HAVE THE TOTAL NUMBER OF EMPLOYEE IN COMPANY, WE CANT COMPREHEND HOW BIG THE COMPANY
-- LETS SAY COMPANY A HAS 1000 EMPLOYEE AND IT HAS 1 PERCENTAGE_LAID_OFF AND COMPANY B HAS 2000 EMPLOYEE AND HAS 20% LAID OFF
-- SINCE WE DONT HAVE TOTAL EMPLOYEE IN OUR DATESET OUR ANALYSIS WILL SHOW COMPANY A HAS HIGHER LAID EMPLOYEE THAN COMPANY IF WE WILL BASED ON PERCENTAGE
-- THATS WHY ITS NOT RELIABLE TO USE PERCENTAGE IF WE DONT HAVE FULL TOTAL OF EMPLOYEE IN COMPANY
SELECT company, SUM(percentage_laid_off)
FROM layoffs_staging2
GROUP BY company
ORDER BY 2 DESC;

-- HERE WE CHECK TOTAL LAID OFF PER MONTH
SELECT SUBSTRING(`date`, 1, 7) AS 'month', SUM(total_laid_off)
FROM layoffs_staging2
WHERE SUBSTRING(`date`, 1, 7) IS NOT NULL
GROUP BY `month`;

-- HERE WE MAKE A ROLLING TOTAL LAID OFF PER MONTH
WITH rolling_total AS
(
SELECT SUBSTRING(`date`, 1, 7) AS 'month', SUM(total_laid_off) AS total_off
FROM layoffs_staging2
WHERE SUBSTRING(`date`, 1, 7) IS NOT NULL
GROUP BY `month`
ORDER BY 1 ASC
)
SELECT `month`, total_off, SUM(total_off) OVER(ORDER BY `month`) AS rolling_total_month
FROM rolling_total;

-- WE CHECK TOTAL LAID OFF OF COMPANY IN YEARS
SELECT company, YEAR(`date`),SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY company, YEAR(`date`)
ORDER BY 2 DESC;

SELECT YEAR(`date`), SUM(total_laid_off)
FROM layoffs_staging2
GROUP BY YEAR(`date`)
ORDER BY 1 DESC;
-- WE USE CTE TO RANK THE TOP 5 COMPANY WHO HAS THE HIGHEST TOTAL LAID OFF EACH YEAR
WITH company_year AS
(
SELECT company, YEAR(`date`) AS 'years', SUM(total_laid_off) AS total_laid_off
FROM layoffs_staging2
GROUP BY company, YEAR(`date`)
),
company_rank AS
(
SELECT *, DENSE_RANK() OVER (PARTITION BY years ORDER BY total_laid_off DESC) AS ranking
FROM company_year
WHERE years IS NOT NULL
)
SELECT *
FROM company_rank
WHERE ranking <= 5;

-- HERE WE CHECK WHAT COMPANIES HAS HIGHEST LAID OFF AND FUNDS RAISED TO 500 MILLION HIGHER
-- BY LOOKING TO PERCENTAGE LAYOFF WE CAN ASSUME IF IT HIT 100% THE COMPANY WENT DOWN AND HERE WE CAN SEE WHOS COMPANY WHEN UNDER AND LOSS HUGE A LOT OF MONEY
SELECT *
FROM layoffs_staging2
WHERE percentage_laid_off = 1
AND funds_raised_millions > 500
ORDER BY funds_raised_millions DESC
;

-- I ALSO CHECK WHAT TOP 3 INDUSTRY HIT THE MOST EACH YEAR FROM 2020-2023
-- I NOTICE IN 2020 TRANSPORTATION AND TRAVEL INDUSTRY HIT THE MOST SINCE 2020 PANDEMIC HIT THE WHOLE WORLD AND ADVISE LOCKDOWN WHERE PEOPLE ARE ADVISED TO STAY AT HOME
WITH industry_year AS
(
SELECT industry, YEAR(`date`) AS 'years', SUM(total_laid_off) AS total_laid_off
FROM layoffs_staging2
GROUP BY industry, YEAR(`date`)
),
industry_rank AS
(
SELECT *, DENSE_RANK() OVER (PARTITION BY years ORDER BY total_laid_off DESC) AS ranking
FROM industry_year
WHERE years IS NOT NULL
)
SELECT *
FROM industry_rank
WHERE ranking <= 3;